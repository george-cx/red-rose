/**
 * Finds every [[PLACEHOLDER]] left in the codebase and rewrites PLACEHOLDERS.md.
 *
 *   pnpm check-placeholders
 *
 * Placeholders are how the site refuses to invent facts: anything the posts do
 * not support is a visible marker, never a plausible-looking guess.
 */

import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, extname } from 'node:path';
import { ROOT } from './source';

const SEARCH = ['src', 'content', 'scripts'];
const EXTENSIONS = new Set(['.ts', '.tsx', '.mdx', '.json', '.css']);

/** The files that implement the mechanism, whose own examples are not gaps. */
const SELF = new Set(['src/components/Placeholder.tsx', 'scripts/check-placeholders.ts']);

/** What each placeholder needs, so the list is actionable rather than a dump. */
const NEEDS: Record<string, string> = {
  HERO_PHOTO: '**Satisfied** — `public/site/exterior-night.jpg` is in place (the group at night in front of the uplit sign) and the home page uses it. The marker survives only as the fallback branch in `Hero.tsx`, shown if that file is ever removed. One caveat: the supplied copy is 1600x1200, which is slightly soft full-bleed on a large retina display. If the original off the phone is available, drop it in over the top and re-run `pnpm prepare-images`.',
  GETTING_HERE: 'The map pin. Open Google Maps, right-click the cellar gate, and the first menu item is the latitude and longitude — paste that pair into `MAP.coords` in `src/lib/contact.ts`. That one line turns on the "Open in Google Maps" link on /visit and /contact and adds `geo` and `hasMap` to the structured data, which is what actually places a business on the map in search results. No public listing for the cellar exists yet, so these cannot be looked up; a guessed pin would send guests to the wrong gate.',
  OTHER_VARIETIES: 'The grape varieties beyond Tsolikouri, Krakhuna, Aladasturi and Aleksandrouli. Post 20 says guests buy wines of several varieties, so there are more.',
  CURRENT_VINTAGES: 'Which vintages are currently available.',
  BOTTLE_FORMATS: 'Bottle sizes sold.',
  PRICE_BOTTLE: 'Deliberately empty. Prices are negotiated per group, so no price appears anywhere on the site. Nothing to fill in unless that changes.',
  ERISTAVI_PRODUCTS: 'Which products the "Eristavi" trademark covers. The posts name only a nine-year cognac (Post 16); the mark may cover more.',
  ERISTAVI_REGISTRATION: 'Registration number, date and jurisdiction for the "Eristavi" mark — the detail trade enquiries will ask for.',
  ERISTAVI_AVAILABILITY: 'Where Eristavi products can be bought, or whether they are cellar-door only.',
  SOCIAL_LINKS: 'The Facebook page URL the posts come from — for the footer and the JSON-LD `sameAs`.',
  SITE_URL: 'The real domain. `src/lib/contact.ts` currently assumes `https://redrose.ge`, which drives every canonical, hreflang and sitemap URL.',
};

function walk(dir: string, out: string[] = []): string[] {
  for (const name of readdirSync(dir)) {
    if (name === 'node_modules' || name.startsWith('.')) continue;
    const full = join(dir, name);
    if (statSync(full).isDirectory()) walk(full, out);
    else if (EXTENSIONS.has(extname(full))) out.push(full);
  }
  return out;
}

function main() {
  const found = new Map<string, Set<string>>();

  for (const base of SEARCH) {
    for (const file of walk(join(ROOT, base))) {
      if (SELF.has(relative(ROOT, file))) continue;
      const text = readFileSync(file, 'utf8');
      // Both the literal [[NAME]] form and <Placeholder name="NAME" />.
      const names = [
        ...[...text.matchAll(/\[\[([A-Z0-9_]+)\]\]/g)].map((m) => m[1]),
        ...[...text.matchAll(/<Placeholder\s+name="([A-Z0-9_]+)"/g)].map((m) => m[1]),
      ];
      for (const name of names) {
        if (!found.has(name)) found.set(name, new Set());
        found.get(name)!.add(relative(ROOT, file));
      }
    }
  }

  // SITE_URL is a constant rather than a marker, but it is just as unresolved.
  found.set('SITE_URL', new Set(['src/lib/contact.ts']));

  const names = [...found.keys()].sort();

  const lines: string[] = [
    '# PLACEHOLDERS.md',
    '',
    '_Generated by `pnpm check-placeholders`. Do not edit by hand._',
    '',
    'Everything the posts do not tell us is a visible placeholder in the site, never a',
    'plausible-looking guess. This is the list, and what each one needs.',
    '',
    `**${names.length} open.**`,
    '',
  ];

  for (const name of names) {
    const files = [...found.get(name)!].sort();
    lines.push(`## \`[[${name}]]\``, '');
    lines.push(NEEDS[name] ?? '_No note recorded._', '');
    lines.push('Appears in:', '');
    for (const file of files) lines.push(`- \`${file}\``);
    lines.push('');
  }

  lines.push('---', '');
  lines.push('## Deliberately not on this list', '');
  lines.push(
    '- **Prices.** Negotiated per group. No price, no "from ₾X", no tiers — anywhere, in any locale.',
    '- **Accommodation.** Never mentioned in the posts, and you asked to skip it. The site says nothing about beds.',
    '- **Dates on posts.** The source dates two posts out of forty-four. The archive is ordered editorially and shows no dates at all.',
    '- **Certification.** Tariel describes his practice in detail but claims no organic or biodynamic certification, so the site claims none.',
    '',
  );

  writeFileSync(join(ROOT, 'PLACEHOLDERS.md'), lines.join('\n'), 'utf8');
  console.log(`check-placeholders: ${names.length} open — written to PLACEHOLDERS.md`);
  for (const name of names) console.log(`  [[${name}]]  ${[...found.get(name)!].length} file(s)`);
}

main();
